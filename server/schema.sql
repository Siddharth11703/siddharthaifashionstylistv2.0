-- Supabase database schema for Siddharth AI Fashion Stylist.
-- Run this SQL in the Supabase SQL editor before starting the server.

CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT UNIQUE NOT NULL,
  phone TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.saved_outfits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  occasion TEXT,
  budget TEXT,
  height TEXT,
  age TEXT,
  body_type TEXT,
  skin_tone TEXT,
  outfit_name TEXT,
  recommendation JSONB,
  outfit_description TEXT,
  outfit_explanation TEXT,
  outfit_image_url TEXT,
  image_url TEXT,
  user_photo_path TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS saved_outfits_user_id_created_at_idx
  ON public.saved_outfits (user_id, created_at DESC);
